// Helper function to get translation key
function getTranslationKey(examSubject: string, chapterNumber: number, examName?: string): string {
  // Check if it's Bacalaureate for Romanian Language and Literature
  if (examName && examName.includes("Bacalaureat") && examSubject.includes("Limba și Literatura Română")) {
    return `${examSubject}|${chapterNumber}-bac`;
  }
  return `${examSubject}|${chapterNumber}`;
}

// Function to get translated chapter
export function getTranslatedChapter(
  examSubject: string,
  chapterNumber: number,
  language: "ro" | "en",
  examName?: string
): { title: string; description: string } | null {
  if (language === "ro") {
    return null; // Return null to use original Romanian
  }
  
  const key = getTranslationKey(examSubject, chapterNumber, examName);
  return chapterTranslations[key] || null;
}

